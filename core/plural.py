"""Согласование существительного с числом.

Лежит в core, а не рядом с местом первого применения: формы нужны и админке
(«5 строк»), и шаблонам («9 модулей»), а штатный `pluralize` Django даёт две
формы и для русского не годится.
"""


def plural_ru(n, one, few, many):
    """1 строка, 2 строки, 5 строк."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many
