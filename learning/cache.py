"""Кэш посчитанных отчётов.

Аналитика собирается тяжело, а меняется медленно: студент проходит урок за минуты,
не за секунды. Держать её в кэше несколько десятков секунд — самый дешёвый способ
пережить момент, когда преподаватель обновляет страницу на паре.

Сброс — **только по времени**. Событийная инвалидация («студент завершил урок →
сбросить отчёты его преподавателя») выглядит аккуратнее, но требует знать, в какие
отчёты входит каждое событие, и первая же забытая связь даёт отчёт, который не
обновляется никогда. Устаревание на минуту в учебной аналитике безвредно, поэтому
выбран вариант, который невозможно сломать незаметно.

`REPORT_CACHE_SECONDS = 0` отключает кэш целиком — так гоняются тесты, где
устаревшие данные означали бы проверку неизвестно чего.
"""

from django.conf import settings
from django.core.cache import cache


def report_key(name, teacher, course=None, **extra):
    """Ключ отчёта. Преподаватель — обязательная часть: отчёты у всех разные."""
    parts = [f"report:{name}", f"t={teacher.pk}", f"c={course.pk if course else '-'}"]
    parts += [f"{k}={v}" for k, v in sorted(extra.items())]
    return "|".join(parts)


def cached_report(key, build):
    """Вернуть отчёт из кэша или построить и запомнить."""
    ttl = getattr(settings, "REPORT_CACHE_SECONDS", 0)
    if not ttl:
        return build()

    value = cache.get(key)
    if value is None:
        value = build()
        cache.set(key, value, ttl)
    return value
