"""Чистая математика учебной аналитики: риск отставания и трудность уроков.

Без обращений к БД — сюда приходят уже посчитанные агрегаты. Так формулы можно
проверять по отдельности, и видно, что именно считается, а не где взялось.

Два блока:

1. **Риск отставания** — перенос формулы из Next-версии без изменений
   (`src/lib/risk.ts`), чтобы результаты двух версий были сопоставимы.
2. **Сопоставление объективной и субъективной трудности** — новое. Это ядро
   исследовательской части: платформа сравнивает, насколько урок труден *по данным*
   и насколько он кажется трудным *студентам*, и показывает расхождение.
"""

# --- 1. Риск отставания ------------------------------------------------------
#
# Взвешенная сумма трёх наблюдаемых признаков. Веса взяты из Next-версии и намеренно
# не менялись: иначе прошлогодние результаты нельзя было бы сравнивать с новыми.
# Формула сознательно простая — её должен понимать преподаватель, а не только автор.

RISK_W_COMPLETION = 0.4  # отставание по программе
RISK_W_SCORE = 0.3  # низкие баллы
RISK_W_INACTIVITY = 0.3  # давно не заходил

# Порог, после которого бездействие считается полным (две недели).
INACTIVITY_CAP_DAYS = 14

RISK_LOW_MAX = 35
RISK_MEDIUM_MAX = 65


def compute_risk(completion, avg_score, days_inactive):
    """Индекс риска 0–100. Чем больше, тем вероятнее, что студент отстаёт.

    `completion` и `avg_score` — проценты 0–100, `days_inactive` — дни с последнего
    события. `None` трактуется как худший случай: у студента без активности вообще
    нет оснований считать, что всё хорошо.
    """
    completion = completion or 0
    avg_score = avg_score or 0
    inactivity = 1.0 if days_inactive is None else min(days_inactive / INACTIVITY_CAP_DAYS, 1.0)

    risk = (
        RISK_W_COMPLETION * (1 - completion / 100)
        + RISK_W_SCORE * (1 - avg_score / 100)
        + RISK_W_INACTIVITY * inactivity
    )
    return round(risk * 100)


def risk_zone(risk):
    """Зона риска: подпись и тон для интерфейса."""
    if risk < RISK_LOW_MAX:
        return {"label": "низкий", "tone": "success"}
    if risk <= RISK_MEDIUM_MAX:
        return {"label": "средний", "tone": "warning"}
    return {"label": "высокий", "tone": "danger"}


# --- 2. Трудность урока: объективная и субъективная --------------------------
#
# Обе величины приводятся к одной шкале 0–100, иначе их нельзя сравнивать:
# субъективная приходит оценкой 1–5, объективная складывается из разнородных метрик.

# Вклады объективной трудности. Сумма весов — 1.
OBJ_W_SCORE = 0.45  # средний балл теста (инвертированный)
OBJ_W_ATTEMPTS = 0.30  # сколько попыток уходит на прохождение
OBJ_W_FAILED = 0.25  # доля неверных решений задания

# Больше трёх попыток на тест — считаем предельной трудностью.
ATTEMPTS_CAP = 3

# Расхождение меньше этого — считаем совпадением. 15 пунктов из 100 примерно
# соответствуют половине шага шкалы 1–5, то есть находятся в пределах точности,
# с которой человек вообще способен оценить трудность.
DIVERGENCE_TOLERANCE = 15


def subjective_difficulty(avg_difficulty_rating):
    """Оценка 1–5 → шкала 0–100. 1 балл → 0, 5 баллов → 100."""
    if avg_difficulty_rating is None:
        return None
    return round((avg_difficulty_rating - 1) / 4 * 100)


def objective_difficulty(avg_score, avg_attempts, failed_share):
    """Индекс объективной трудности 0–100 по данным о прохождении.

    - `avg_score` — средний балл теста, 0–100 (инвертируется: низкий балл = трудно);
    - `avg_attempts` — среднее число попыток теста на студента (1 = с первого раза);
    - `failed_share` — доля неверных решений заданий урока, 0–1.

    Отсутствующие составляющие не обнуляются, а **исключаются с перевесом
    остальных**: урок без заданий не должен выглядеть проще урока с заданиями лишь
    потому, что одного слагаемого нет.
    """
    parts = []
    if avg_score is not None:
        parts.append((OBJ_W_SCORE, 1 - avg_score / 100))
    if avg_attempts is not None:
        extra = max(avg_attempts - 1, 0)
        parts.append((OBJ_W_ATTEMPTS, min(extra / (ATTEMPTS_CAP - 1), 1.0)))
    if failed_share is not None:
        parts.append((OBJ_W_FAILED, min(max(failed_share, 0.0), 1.0)))

    if not parts:
        return None
    total_weight = sum(w for w, _ in parts)
    value = sum(w * v for w, v in parts) / total_weight
    return round(value * 100)


def divergence(objective, subjective):
    """Расхождение и его педагогический смысл.

    Возвращает `{"delta", "label", "tone", "comment"}` либо `None`, если одной из
    величин нет.

    Знак важен и читается так:

    - **объективно труднее, чем кажется** (`delta > 0`) — студенты недооценивают
      трудность. Самый неприятный случай: человек уверен, что понял, и не
      возвращается к теме, а данные говорят обратное. Такой урок стоит закрепить
      дополнительной практикой;
    - **кажется труднее, чем есть** (`delta < 0`) — студенты переоценивают трудность.
      Справляются, но не чувствуют этого; здесь нужнее не объяснение, а обратная
      связь и уверенность.
    """
    if objective is None or subjective is None:
        return None

    delta = objective - subjective
    if abs(delta) <= DIVERGENCE_TOLERANCE:
        return {
            "delta": delta,
            "label": "совпадает",
            "tone": "success",
            "comment": "Ощущения студентов совпадают с данными.",
        }
    if delta > 0:
        return {
            "delta": delta,
            "label": "недооценивают",
            "tone": "danger",
            "comment": (
                "Объективно урок труднее, чем кажется студентам: они уверены, что "
                "разобрались, а данные говорят иначе. Стоит добавить практики "
                "и вернуться к теме позже."
            ),
        }
    return {
        "delta": delta,
        "label": "переоценивают",
        "tone": "warning",
        "comment": (
            "Урок кажется студентам труднее, чем показывают результаты: они "
            "справляются, но не чувствуют уверенности. Полезнее не переобъяснять, "
            "а показать им их собственный прогресс."
        ),
    }


def mastery_zone(pct_correct):
    """Зона освоения темы по доле верных ответов."""
    if pct_correct is None:
        return {"label": "нет данных", "tone": "muted"}
    if pct_correct >= 80:
        return {"label": "освоена", "tone": "success"}
    if pct_correct >= 60:
        return {"label": "частично", "tone": "warning"}
    return {"label": "провал", "tone": "danger"}
