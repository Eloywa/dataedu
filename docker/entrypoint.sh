#!/bin/sh
# Подготовка контейнера приложения перед запуском gunicorn.
set -e

STATIC_VOLUME=/var/www/static

# Статика собрана в образ на этапе сборки. Здесь она копируется в том, из
# которого её отдаёт nginx.
#
# Именованный том Docker наполняет из образа только при первом создании: после
# выката новой версии старый том остался бы с прежними файлами, а разметка уже
# ссылалась бы на новые имена с хешами — страница пришла бы без стилей. Поэтому
# копируем при каждом запуске, а не полагаемся на первичное наполнение.
if [ -d "$STATIC_VOLUME" ]; then
    echo "Обновляю статику в $STATIC_VOLUME"
    cp -a /app/staticfiles/. "$STATIC_VOLUME"/
fi

# Миграции — только перед запуском самого приложения. Разовые команды
# (`docker run … python manage.py shell`) не должны тянуть за собой миграцию:
# она бы выполнилась молча и не тогда, когда её ждут.
#
# Для одного экземпляра миграция при старте удобна и безопасна; если когда-нибудь
# появится второй, её надо будет вынести в отдельный шаг выката — иначе два
# процесса возьмутся за схему одновременно.
case "$1" in
    gunicorn)
        if [ "${RUN_MIGRATIONS:-1}" = "1" ]; then
            echo "Применяю миграции"
            python manage.py migrate --noinput
        fi
        ;;
esac

exec "$@"
