"""Обложка курса: фотография, если она для курса подобрана, иначе градиент.

Фотографии лежат в `static/img/covers/` и отдаются с того же сервера — правило
«ноль внешних запросов» действует и здесь, ссылаться на чужой хостинг нельзя.
Происхождение и лицензия каждого снимка записаны в `static/img/covers/README.md`;
для дипломной работы это существенно, поэтому файл ведётся вместе с картинками.

Восемь курсов из дампа получили предметные снимки — картотека, склад, чертёж,
хранилище. Отвлечённые «кибер»-иллюстрации сознательно не брались: к теме они не
ближе градиента, а выглядят как заставка из презентации.

Для курса без подобранного снимка (преподаватель завёл свой) остаётся прежняя
рисованная обложка: градиент по slug и тематическая иконка. Она ничего не весит
и не требует, чтобы кто-то искал картинку перед публикацией.

Градиент выбирается по хешу slug, то есть у курса он постоянный: обложка не
«прыгает» между открытиями страницы и узнаётся в каталоге.

Палитра насыщенная и разноцветная — карточки должны различаться с одного взгляда.
Прежний набор был подобран под тёмный «терминальный» вид: восемь почти чёрных
градиентов, которые на светлом листе читались как грязные пятна и сливались
между собой.
"""

import hashlib

# Пары «от — до» для линейного градиента. Тона выбраны средней тёмности: белая
# иконка поверх должна оставаться контрастной, а сама плашка — не спорить
# с текстом карточки под ней.
GRADIENTS = [
    ("#1d4ed8", "#3b82f6"),  # синий
    ("#0f766e", "#14b8a6"),  # бирюзовый
    ("#7c3aed", "#a78bfa"),  # фиолетовый
    ("#b45309", "#f59e0b"),  # янтарный
    ("#be123c", "#f43f5e"),  # малиновый
    ("#15803d", "#4ade80"),  # зелёный
    ("#0e7490", "#22d3ee"),  # голубой
    ("#4338ca", "#818cf8"),  # индиго
]

ICONS = {
    "database": '<ellipse cx="12" cy="5" rx="8" ry="3"/><path d="M4 5v14c0 1.7 3.6 3 8 3s8-1.3 8-3V5"/><path d="M4 12c0 1.7 3.6 3 8 3s8-1.3 8-3"/>',
    "table": '<rect x="3" y="4" width="18" height="16" rx="1.5"/><path d="M3 9h18M3 14.5h18M9 4v16M15 4v16"/>',
    "key": '<circle cx="8" cy="8" r="3.5"/><path d="M10.5 10.5L19 19M14 18l2-2M16 16l2.5-2.5"/>',
    "bolt": '<path d="M13 2L4 14h7l-1 8 9-12h-7l1-8z"/>',
    "lock": '<rect x="5" y="11" width="14" height="9" rx="2"/><path d="M8 11V7a4 4 0 0 1 8 0v4"/>',
    "layers": '<path d="M12 3l9 5-9 5-9-5 9-5z"/><path d="M3 13l9 5 9-5"/>',
    "window": '<rect x="3" y="4" width="18" height="16" rx="1.5"/><path d="M3 9h18M7 16.5v-3M11 16.5v-5M15 16.5v-2M19 16.5v-4"/>',
}

SLUG_ICON = {
    "sql-s-nulya": "table",
    "databases-for-teachers": "database",
    "postgresql-praktika": "database",
    "proektirovanie-er": "key",
    "normalizaciya": "layers",
    "indeksy-proizvoditelnost": "bolt",
    "okonnye-funkcii": "window",
    "tranzakcii-blokirovki": "lock",
}


# Курсы, для которых подобран снимок. Перечислены явно, а не собираются обходом
# каталога: обложка — часть оформления, и появление файла в папке не должно
# менять вид карточки само по себе, без правки кода.
PHOTOS = {
    "sql-s-nulya",
    "databases-for-teachers",
    "postgresql-praktika",
    "proektirovanie-er",
    "normalizaciya",
    "indeksy-proizvoditelnost",
    "okonnye-funkcii",
    "tranzakcii-blokirovki",
}


def cover_for(slug):
    h = int(hashlib.md5((slug or "").encode()).hexdigest(), 16)
    a, b = GRADIENTS[h % len(GRADIENTS)]
    icon = ICONS[SLUG_ICON.get(slug, "database")]
    return a, b, icon


def photo_for(slug):
    """Путь к снимку внутри static или None, если для курса его нет."""
    return f"img/covers/{slug}.jpg" if slug in PHOTOS else None
