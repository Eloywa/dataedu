// Согласование существительного с числом по-русски: 1 строка, 2 строки, 5 строк.
// Отдельным модулем, потому что нужно и тренажёру, и автопроверке, а дублировать
// правило в двух островках — верный способ поправить его только в одном.
export function pluralRu(n, one, few, many) {
  const v = Math.abs(Math.trunc(n));
  if (v % 10 === 1 && v % 100 !== 11) return one;
  if (v % 10 >= 2 && v % 10 <= 4 && !(v % 100 >= 12 && v % 100 <= 14)) return few;
  return many;
}

export function rowsLabel(n) {
  return `${n} ${pluralRu(n, "строка", "строки", "строк")}`;
}
