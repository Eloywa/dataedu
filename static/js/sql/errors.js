// Разбор ошибок PostgreSQL.
//
// Сообщения приходят по-английски и в терминах движка: «relation does not exist»
// ничего не говорит второкурснику, который ищет опечатку в названии таблицы.
// Здесь — перевод самых частых на язык учебной задачи. Оригинал всегда остаётся
// рядом: умение читать вывод СУБД — тоже часть курса, прятать его нельзя.
//
// Кроме подсказки правило отдаёт код. Код уходит на сервер (сам SQL и текст
// ошибки — нет) и складывается в статистику: на чём именно спотыкаются студенты
// конкретного урока. Это третий объективный признак трудности рядом с баллами и
// числом попыток — и в отличие от них он говорит не «трудно», а «что именно».

const RULES = [
  {
    code: "no_table",
    test: /relation "(.+?)" does not exist/i,
    hint: (m) => `Таблицы «${m[1]}» в базе нет. Проверьте название — список таблиц слева.`,
  },
  {
    code: "no_column",
    test: /column "?(.+?)"? does not exist/i,
    hint: (m) => `Столбца «${m[1]}» нет. Разверните таблицу в списке слева, чтобы увидеть её столбцы.`,
  },
  {
    code: "group_by",
    test: /column (.+?) must appear in the GROUP BY/i,
    hint: (m) =>
      `Столбец ${m[1]} не агрегирован: при GROUP BY каждый столбец из SELECT либо ` +
      "перечислен в группировке, либо обёрнут в агрегат — count, sum, avg.",
  },
  {
    code: "syntax",
    test: /syntax error at or near "(.+?)"/i,
    hint: (m) =>
      `Синтаксическая ошибка около «${m[1]}». Обычно причина раньше этого места: ` +
      "пропущенная запятая, скобка или ключевое слово.",
  },
  {
    code: "types",
    test: /operator does not exist: (.+)/i,
    hint: (m) =>
      `Несовместимые типы в сравнении (${m[1]}). Число со строкой напрямую сравнивать ` +
      "нельзя — приведите тип через CAST или ::.",
  },
  {
    code: "ambiguous",
    test: /column reference "(.+?)" is ambiguous/i,
    hint: (m) =>
      `Столбец «${m[1]}» есть в обеих соединяемых таблицах, и непонятно, какой имеется ` +
      "в виду. Укажите таблицу или её псевдоним: s.id вместо id.",
  },
  {
    code: "div_zero",
    test: /division by zero/i,
    hint: () => "Деление на ноль. Отсеките нулевой делитель через NULLIF или условие в WHERE.",
  },
  {
    code: "unique",
    test: /duplicate key value violates unique constraint/i,
    hint: () =>
      "Такое значение уже есть, а столбец объявлен уникальным. Это и есть ограничение " +
      "целостности в работе.",
  },
  {
    code: "not_null",
    test: /null value in column "(.+?)".*not-null/i,
    hint: (m) => `Столбец «${m[1]}» объявлен NOT NULL — значение обязательно.`,
  },
  {
    code: "foreign_key",
    test: /violates foreign key constraint/i,
    hint: () =>
      "Внешний ключ ссылается на несуществующую строку. Сначала добавьте запись в " +
      "таблицу, на которую ссылаетесь.",
  },
  {
    code: "check",
    test: /violates check constraint/i,
    hint: () =>
      "Значение не проходит проверку CHECK, записанную в определении таблицы. " +
      "Посмотрите её условие и допустимый диапазон.",
  },
  {
    code: "denied",
    test: /permission denied|must be owner/i,
    hint: () =>
      "Операция запрещена. В песочнице доступны обычные запросы и работа с таблицами, " +
      "но не администрирование сервера.",
  },
];

/**
 * Разбирает сообщение PostgreSQL.
 * @returns {{code: string, hint: string|null}} код класса ошибки и пояснение.
 *          Для неопознанного сообщения — код "other" и отсутствие подсказки:
 *          выдумывать объяснение хуже, чем не дать никакого.
 */
export function classify(message) {
  const text = String(message || "");
  for (const rule of RULES) {
    const m = rule.test.exec(text);
    if (m) return { code: rule.code, hint: rule.hint(m) };
  }
  return { code: "other", hint: null };
}

/** Названия классов ошибок для отчётов. Держится рядом с правилами намеренно:
 *  разъехавшись, список и правила дадут отчёт с пустыми строками. */
export const ERROR_TITLES = {
  no_table: "Нет такой таблицы",
  no_column: "Нет такого столбца",
  group_by: "Столбец не в GROUP BY",
  syntax: "Синтаксис",
  types: "Несовместимые типы",
  ambiguous: "Неоднозначный столбец",
  div_zero: "Деление на ноль",
  unique: "Нарушение уникальности",
  not_null: "NOT NULL",
  foreign_key: "Внешний ключ",
  check: "Нарушение CHECK",
  denied: "Операция запрещена",
  other: "Прочее",
};
