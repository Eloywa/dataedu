def topic_description(area, entities, questions):
    lines = [area, "", f"Что учесть: {entities}.", "", "На какие вопросы должна отвечать база:"]
    lines.extend(
        f"{number}. {question[0].upper()}{question[1:]}."
        for number, question in enumerate(questions, 1)
    )
    return "\n".join(lines)


class Command(BaseCommand):
    help = "Создать задания к блокам 4–7 основного курса и темы билетов итогового проекта."

    def handle(self, *args, **options):
        course = Course.objects.filter(slug=COURSE_SLUG).first()
        if course is None:
            self.stderr.write(f"Курс {COURSE_SLUG} не найден — сначала загрузите содержимое.")
            return

        tasks, skipped = 0, []
        for task in TASKS:
            lesson = Lesson.objects.filter(module__course=course, title=task["lesson"]).first()
            if lesson is None:
                skipped.append(task["lesson"])
                continue
            setup = SETUP + task.get("extra_setup", "")
            Assignment.objects.update_or_create(
                course=course,
                title=task["title"],
                defaults={
                    "lesson": lesson,
                    "description": task["description"],
                    "level": task["level"],
                    "type": "sql",
                    "setup_sql": setup,
                    "expected_sql": task["expected_sql"],
                    "expected_result": task["expected_result"],
                    "max_score": 10,
                    "is_final": False,
                },
            )
            tasks += 1

        for title, area, entities, questions in TOPICS:
            ProjectTopic.objects.update_or_create(
                course=course,
                title=title,
                defaults={"description": topic_description(area, entities, questions)},
            )

        finals = Assignment.objects.filter(course=course, is_final=True)
        opens_after = Module.objects.filter(course=course, title=OPENS_AFTER_MODULE).first()
        finals.update(description=FINAL_DESCRIPTION, opens_after=opens_after)

        if options["verbosity"]:
            self.stdout.write(self.style.SUCCESS(f"Заданий: {tasks}; тем билетов: {len(TOPICS)}."))
        for title in skipped:
            self.stderr.write(f"Урок не найден, задание пропущено: {title}")
